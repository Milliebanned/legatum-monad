// Local-testing-only deployment. Deploys VaultFactory, KeeperReceiver and two
// test stablecoins to a `npx hardhat node` instance, mints test tokens to the
// first local accounts and writes the addresses to
// frontend/src/deployedLocal.js for `npm run dev:local`.
//
// Usage:
//   npx hardhat run script/deploy-local.js --network localhost
const fs = require("fs");
const path = require("path");
const { ethers, network } = require("hardhat");

async function deploy(name, ...args) {
  const contract = await (await ethers.getContractFactory(name)).deploy(...args);
  await contract.waitForDeployment();
  return contract;
}

async function main() {
  if (network.name !== "localhost" && network.name !== "hardhat") {
    throw new Error(`Refusing to run the local deploy script against "${network.name}".`);
  }

  const signers = await ethers.getSigners();
  console.log(`Deploying to network "${network.name}" as ${signers[0].address}`);

  const usdc = await deploy("TestToken", "Test USDC", "USDC", 6);
  const ausd = await deploy("TestToken", "Test AUSD", "AUSD", 6);
  const factory = await deploy("VaultFactory");
  const receiver = await deploy("KeeperReceiver");

  const mintAmount = ethers.parseUnits("10000", 6);
  for (const signer of signers.slice(0, 5)) {
    await (await usdc.mint(signer.address, mintAmount)).wait();
    await (await ausd.mint(signer.address, mintAmount)).wait();
  }
  console.log(`Minted 10,000 test USDC and AUSD to ${Math.min(5, signers.length)} local accounts`);

  const addresses = {
    factory: await factory.getAddress(),
    keeperReceiver: await receiver.getAddress(),
    usdc: await usdc.getAddress(),
    ausd: await ausd.getAddress(),
  };
  for (const [key, address] of Object.entries(addresses)) console.log(`${key}: ${address}`);

  fs.writeFileSync(
    path.join(__dirname, "..", "frontend", "src", "deployedLocal.js"),
    `// Auto-generated by script/deploy-local.js. Local Hardhat-node testing only.
export default {
${Object.entries(addresses)
  .map(([key, address]) => `  ${key}: "${address}",`)
  .join("\n")}
};
`
  );
  console.log("Wrote frontend/src/deployedLocal.js");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
